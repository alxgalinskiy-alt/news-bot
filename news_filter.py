#!/usr/bin/env python3
"""Тематический фильтр дайджеста: отсекает новости, не относящиеся к enterprise-рынку.

Логика — «чёрный список»: новость проходит, пока не совпала с шаблоном мусора.
Так безопаснее белого списка: незнакомая, но важная тема не потеряется.

Три ручки настройки у каждого правила:

  scope    — где искать совпадение:
             "text"  — слова, которые сами по себе выдают тему («студент», «подработка»).
             "title" — неоднозначные слова («университет», «игра»). Они часто мелькают
                       в описании новости совсем на другую тему: у CIO «Росатома»
                       в биографии есть университет. Тему задаёт заголовок — там и ищем.
             "lead"  — первое предложение заголовка. Нужно для бытовой техники:
                       у CNews в хвосте заголовка часто висит уточнение, и «смартфон»
                       там оказывается случайно («Российский навигатор работает
                       по приборам, которые есть даже в самых дешёвых смартфонах» —
                       новость про навигацию, а не про смартфоны).

  strength — HARD отсекает всегда; SOFT отсекает, только если в тексте нет
             корпоративного маркера (ENTERPRISE_RESCUE). Благодаря этому
             «предзаказ на смартфоны» уходит, а «поставка ноутбуков корпоративным
             клиентам» и «серверные процессоры» остаются.

Проверить на живых лентах:  python3 news_filter.py --check
Проверить свой заголовок:   python3 news_filter.py --test "заголовок новости"
"""
import re
import sys
from typing import List, NamedTuple, Tuple

# --- Корпоративные маркеры: отменяют SOFT-правила -----------------------------
ENTERPRISE_RESCUE = re.compile(
    r"""
    корпоратив | \bb2b\b | b2b- | enterprise | \bсервер | \bцод\b | дата-?центр |
    \bсубд\b | базы?\ данных | кластер | виртуализац |
    импортозамещ | госсектор | госзакуп | госорган | госсервис | госсистем | ведомств |
    промышленн | предприяти | производств | \bзавод |
    кибербезопасн | информационн\ безопасн | \bdlp\b | \bsiem\b |
    аутентификац | двухфакторн | шифрован | \bфстэк\b |
    интегратор | внедрил | внедрен | \berp\b | \bcrm\b | \bmdm\b |
    бизнес-клиент | юридическ\ лиц | для\ бизнеса | оптов
    """,
    re.IGNORECASE | re.VERBOSE,
)

# Явное упоминание России отменяет правила из RUSSIA_EXEMPT: экспортные
# ограничения, санкции и уход зарубежного вендора влияют на наш рынок — такое нужно.
RUSSIA_MARKER = re.compile(r"росси|\bрф\b|российск|отечественн", re.IGNORECASE)
RUSSIA_EXEMPT = {"зарубежная политика", "зарубежные вендоры"}


class Rule(NamedTuple):
    name: str
    strength: str   # HARD | SOFT
    scope: str      # text | title | lead
    pattern: re.Pattern


# Сокращения, после которых точка не заканчивает предложение.
# Без этого «Для 35 тыс. пользователей „Юрент“…» обрезается до «Для 35 тыс.»,
# и правила ищут совпадение в огрызке заголовка.
ABBREVIATIONS = {
    "тыс", "млн", "млрд", "трлн", "руб", "коп", "шт", "проц",
    "гг", "вв", "им", "ул", "стр", "изд", "др", "пр", "рис", "табл",
    "кв", "куб", "см", "мм", "км", "кг", "гб", "тб", "мб", "мин", "сек",
}


def _lead(title: str) -> str:
    """Первое предложение заголовка — то, о чём новость на самом деле.

    Точка сама по себе не значит конец предложения: в заголовках полно
    сокращений («35 тыс. пользователей», «9,2 млрд руб.») и инициалов.
    Считаем границей только точку, после которой идёт заглавная буква,
    а перед ней — не сокращение и не одиночная буква.
    """
    if not title:
        return ""
    text = title.strip()
    for match in re.finditer(r"([.!?])\s+", text):
        if match.group(1) == ".":
            before = text[: match.start()]
            last_word = re.search(r"(\w+)$", before)
            word = last_word.group(1).lower() if last_word else ""
            if word in ABBREVIATIONS or len(word) == 1:
                continue  # сокращение или инициал
            nxt = text[match.end(): match.end() + 1]
            if nxt and not nxt.isupper():
                continue  # предложение так не начинают
        return text[: match.start() + 1].strip()
    return text


