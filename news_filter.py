#!/usr/bin/env python3
"""Тематический фильтр дайджеста: отсекает новости, не относящиеся к enterprise-рынку.

Логика — «чёрный список»: новость проходит, пока не совпала с шаблоном мусора.
Так безопаснее белого списка: незнакомая, но важная тема не потеряется.

Три ручки настройки у каждого правила:

  scope    — где искать совпадение:
             "text"  — слова, которые сами по себе выдают тему («студент», «подработка»).
             "title" — неоднозначные слова («университет», «игра»). Они часто мелькают
                       в описании новости совсем на другую тему: у CIO «Росатома»
                       в биографии есть университет. Тему задаёт заголовок — там и ищем.
             "lead"  — первое предложение заголовка. Нужно для бытовой техники:
                       у CNews в хвосте заголовка часто висит уточнение, и «смартфон»
                       там оказывается случайно («Российский навигатор работает
                       по приборам, которые есть даже в самых дешёвых смартфонах» —
                       новость про навигацию, а не про смартфоны).

  strength — HARD отсекает всегда; SOFT отсекает, только если в тексте нет
             корпоративного маркера (ENTERPRISE_RESCUE). Благодаря этому
             «предзаказ на смартфоны» уходит, а «поставка ноутбуков корпоративным
             клиентам» и «серверные процессоры» остаются.

Проверить на живых лентах:  python3 news_filter.py --check
Проверить свой заголовок:   python3 news_filter.py --test "заголовок новости"
"""
import re
import sys
from typing import List, NamedTuple, Tuple

# --- Корпоративные маркеры: отменяют SOFT-правила -----------------------------
ENTERPRISE_RESCUE = re.compile(
    r"""
    корпоратив | \bb2b\b | b2b- | enterprise | \bсервер | \bцод\b | дата-?центр |
    \bсубд\b | базы?\ данных | облач | кластер | виртуализац |
    импортозамещ | госсектор | госзакуп | госорган | госсервис | госсистем | ведомств |
    промышленн | предприяти | производств | \bзавод |
    кибербезопасн | информационн\ безопасн | \bdlp\b | \bsiem\b |
    интегратор | внедрил | внедрен | \berp\b | \bcrm\b | \bmdm\b |
    бизнес-клиент | юридическ\ лиц | для\ бизнеса | оптов
    """,
    re.IGNORECASE | re.VERBOSE,
)

# Явное упоминание России отменяет правило «зарубежная политика»:
# экспортные ограничения и санкции, влияющие на наш рынок, нужны.
RUSSIA_MARKER = re.compile(r"росси|\bрф\b|российск|отечественн", re.IGNORECASE)


class Rule(NamedTuple):
    name: str
    strength: str   # HARD | SOFT
    scope: str      # text | title | lead
    pattern: re.Pattern


def _lead(title: str) -> str:
    """Первое предложение заголовка — то, о чём новость на самом деле."""
    return re.split(r"(?<=[.!?])\s+", title.strip())[0] if title else ""


RULES: List[Rule] = [
    # --- Образование ---------------------------------------------------------
    # Слова о людях учащихся однозначны — ищем во всём тексте.
    Rule("образование", "HARD", "text", re.compile(
        r"""
        \bстудент | \bабитуриент | \bшкольник | \bшкольн | \bучащ |
        первокурс | \bстипенди | приёмн\ кампан | приемн\ кампан |
        \bдипломн\ работ | \bкурсов\ работ
        """, re.IGNORECASE | re.VERBOSE)),
    # Названия учебных заведений — только в заголовке: в описании они попадаются
    # у любого эксперта в биографии.
    Rule("образование", "HARD", "title", re.compile(
        r"""
        \bвуз\b | \bвуза | \bвузы | \bвузов | \bвузе | университет | \bинститут |
        \bбакалавр | \bмагистрат | \bколледж | \bученик | \bвыпускник
        """, re.IGNORECASE | re.VERBOSE)),

    # --- HR и рынок труда ----------------------------------------------------
    # SOFT: «госсервис выдачи зарплат» — это госИТ-проект, а не HR-новость.
    # Массовые увольнения в ИТ-компаниях сознательно НЕ включены: это сигнал
    # состояния рынка, а не кадровая заметка.
    Rule("HR и рынок труда", "SOFT", "text", re.compile(
        r"""
        трудоустройств | \bваканси | \bрезюме\b | соискател | \bрекрут |
        \bhr\b | hr- | кадров\ агентств | подработк | \bнайм\b | найма\b |
        работодател | \bзарплат | \bоклад\b | собеседован | \bкарьер |
        \bстажировк | рынок\ труда | \bфриланс | \bсоискан
        """, re.IGNORECASE | re.VERBOSE)),

    # --- Быт и частные лица --------------------------------------------------
    Rule("быт и частные лица", "HARD", "text", re.compile(
        r"""
        \bродител | \bдети\b | \bдетей\b | \bдетям | \bдетьми | \bдетях\b |
        \bребён | \bребен | \bдетск | \bмалыш | \bподростк |
        \bсем(ья|ьи|ье|ьёй|ьей|ей)\b | домохозяйств | \bбабушк | \bдедушк |
        \bпенсионер | \bдачник | \bогородн | для\ дома\b | \bжкх\b
        """, re.IGNORECASE | re.VERBOSE)),

    # --- Игры ----------------------------------------------------------------
    # Только заголовок: «игровой ноутбук» в описании не делает новость игровой.
    Rule("игры", "HARD", "title", re.compile(
        r"""
        \bигр(а|ы|у|е|ой|ам|ах|овой|овая|овые|овых|оков|ок|оки)\b |
        видеоигр | геймер | \bгейминг | gamedev | \bxbox | playstation |
        \bps5\b | nintendo | \bsteam\b | киберспорт | \bммо\b | \bgta\b
        """, re.IGNORECASE | re.VERBOSE)),

    # --- Зарубежная политика без влияния на российский рынок -----------------
    Rule("зарубежная политика", "HARD", "text", re.compile(
        r"""
        противостояни | торгов\ войн | \bпошлин | эмбарго |
        \bконгресс | сенат\ сша | белый\ дом |
        администрац\ (сша|трамп|байден) | президент\ (сша|кнр|китая) |
        выбор\ (в\ сша|президент)
        """, re.IGNORECASE | re.VERBOSE)),

    # --- Потребительские устройства ------------------------------------------
    Rule("потребительские устройства", "SOFT", "lead", re.compile(
        r"""
        \bсмартфон | \bпылесос | \bхолодильник | стиральн | \bтелевизор |
        \bнаушник | \bприставк | умн(ая|ой)\ колонк | \bфитнес-браслет |
        смарт-?час | \bмикроволнов | \bкофемашин | бытов(ая|ой)\ техник |
        \bпредзаказ | старт\ продаж | поступил\ в\ продаж | вышел\ в\ продаж |
        \bм\.?видео | \bэльдорадо | розничн\ прода
        """, re.IGNORECASE | re.VERBOSE)),

    # --- Потребительские сервисы ---------------------------------------------
    # Узко: только пользовательские фичи массовых сервисов.
    # Беспилотное такси и подобные разработки сюда сознательно не попадают.
    Rule("потребительские сервисы", "SOFT", "lead", re.compile(
        r"""
        \bалиса\b | алис(е|ы|ой)\b | яндекс\ карт | яндекс\ go | яндекс\ музык |
        \bдоставк\ еды | вк\ музык | подписк\ для\ пользовател | для\ абонентов\b
        """, re.IGNORECASE | re.VERBOSE)),
]


def classify(title: str, phrase: str = "") -> Tuple[bool, str]:
    """Возвращает (пропустить_ли, причина).

    Причина попадает в лог GitHub Actions — по ней видно, за что отсеяна новость,
    и легко понять, надо ли править правило.
    """
    title = title or ""
    text = f"{title} {phrase}".strip()

    for rule in RULES:
        haystack = {"title": title, "lead": _lead(title)}.get(rule.scope, text)
        match = rule.pattern.search(haystack)
        if not match:
            continue

        if rule.name == "зарубежная политика" and RUSSIA_MARKER.search(text):
            continue  # влияет на российский рынок — оставляем
        if rule.strength == "SOFT" and ENTERPRISE_RESCUE.search(text):
            continue  # корпоративный контекст перевешивает

        return False, f"{rule.name} ('{match.group(0).strip()}')"

    return True, ""


# --- Проверка на живых лентах -------------------------------------------------
def _check_live(limit: int = 400) -> int:
    import news_bot

    items = []
    for feed in news_bot.FEEDS:
        try:
            items.extend(news_bot.fetch_feed(feed))
        except Exception as exc:
            print(f"Пропускаю {feed['name']}: {exc}", file=sys.stderr)

    items = sorted(items, key=lambda x: x["ts"], reverse=True)[:limit]

    kept, dropped = [], []
    for item in items:
        phrase = news_bot.make_phrase(item["_entry"], item["title"])
        ok, reason = classify(item["title"], phrase)
        (kept if ok else dropped).append((item, reason))

    print(f"\n{'='*70}\nОТСЕЯНО ({len(dropped)}):\n{'='*70}")
    for item, reason in dropped:
        print(f"  ✗ [{reason}] {item['title'][:95]}")

    print(f"\n{'='*70}\nОСТАНЕТСЯ В ДАЙДЖЕСТЕ ({len(kept)}):\n{'='*70}")
    for item, _ in kept:
        print(f"  ✓ {item['title'][:95]}")

    total = len(items)
    if total:
        print(f"\nИтого: {total} новостей → останется {len(kept)} "
              f"({len(kept)*100//total}%), отсеяно {len(dropped)}.")
    return 0


def main() -> int:
    if "--check" in sys.argv:
        return _check_live()
    if "--test" in sys.argv:
        idx = sys.argv.index("--test")
        text = " ".join(sys.argv[idx + 1:])
        ok, reason = classify(text)
        print(f"{'✓ ПРОЙДЁТ' if ok else '✗ ОТСЕЕТСЯ — ' + reason}: {text}")
        return 0
    print(__doc__)
    return 0


if __name__ == "__main__":
    sys.exit(main())
