def main() -> int:
    failures = []

    for title, phrase in JUNK:
        ok, _ = classify(title, phrase)
        if ok:
            failures.append(("должна была отсеяться", title))

    for title, phrase in USEFUL:
        ok, reason = classify(title, phrase)
        if not ok:
            failures.append((f"отсеяна зря [{reason}]", title))

    total = len(JUNK) + len(USEFUL)
    if failures:
        print(f"❌ Провалено {len(failures)} из {total}:\n")
        for problem, title in failures:
            print(f"  {problem}: {title[:80]}")
        return 1

    print(f"✅ Все {total} проверок пройдены "
          f"({len(JUNK)} мусорных отсеяны, {len(USEFUL)} полезных прошли).")
    return 0


